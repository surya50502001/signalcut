# --- Pydantic Request & Response Models ---

class TranscriptChunkItem(BaseModel):
    chunkIndex: int
    startTime: float
    endTime: float
    text: str
    speaker: str = "Speaker"
    confidence: float = 0.98

class TranscriptionRequest(BaseModel):
    sourceUrl: str
    language: str = "en"
    detectSpeakers: bool = True

class TranscriptionResponse(BaseModel):
    fullText: str
    language: str
    wordCount: int
    chunks: List[TranscriptChunkItem]
    isAutoGenerated: bool
    provider: str

class AnalyzeRequest(BaseModel):
    transcriptText: str
    topicQuery: str
    maxTokens: int = 1500

class MomentDetectionRequest(BaseModel):
    transcriptText: str
    topicQuery: str
    objective: str = "Educational"

class MomentItem(BaseModel):
    startTime: float
    endTime: float
    transcriptSnippet: str
    reason: str
    topicRelevance: float
    hookStrength: float
    informationDensity: float
    clipScore: float
    speaker: str
    confidence: float
    objective: str
    suggestedHook: str
    suggestedTitle: str
    suggestedCaption: str
    suggestedDescription: str
    suggestedHashtags: List[str]
    suggestedCta: str

class RenderClipRequest(BaseModel):
    clipId: str
    sourceVideoUrl: str
    startTime: float
    endTime: float
    aspectRatio: str = "9:16"
    width: int = 1080
    height: int = 1920
    hasWatermark: bool = False
    captionStyle: str = "TIKTOK_POP"
    fontName: str = "Inter"
    fontSize: int = 42
    primaryColorHex: str = "#FFFFFF"
    highlightColorHex: str = "#FACC15"
    backgroundColorHex: str = "#000000"
    logoUrl: Optional[str] = None
    showProgressBar: bool = True
    captions: List[TranscriptChunkItem] = []

class RenderClipResponse(BaseModel):
    success: bool
    storageKey: str
    storageUrl: str
    thumbnailUrl: Optional[str] = None
    durationSeconds: float
    errorMessage: Optional[str] = None


